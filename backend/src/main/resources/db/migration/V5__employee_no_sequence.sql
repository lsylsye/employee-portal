-- 새 직원 사번 발급용 시퀀스. 시드가 EMP-001~010 을 쓰므로 11 부터 시작한다.
-- "최댓값 + 1"은 동시에 등록하면 같은 번호가 나올 수 있어서 시퀀스를 쓴다. 중복은 employee_no_uk 가 최종 방어한다.
-- 형식('EMP-' + 3자리 0 채움)은 애플리케이션에서 만든다. SQL lpad(n, 3, '0')는 1000 부터 '100' 으로 잘려 중복된다.
-- 시퀀스 값은 롤백돼도 되돌아가지 않아 빈 번호가 생길 수 있다(중복보다 낫다).

CREATE SEQUENCE employee_no_seq START WITH 11;
